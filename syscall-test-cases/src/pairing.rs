struct Pairing {
    input: Vec<u8>,
    output: [u8; 32],
}

pub fn prepare<const REPEATS: usize>() -> Box<dyn Workload> {
    Box::new(Pairing {
        input: PAIR.repeat(REPEATS),
        output: [0; 32],
    })
}

impl Workload for Pairing {
    fn invoke_and_check(&mut self) -> Result<(), Error> {
        self.output.fill(0xff);
        #[cfg(target_os = "solana")]
        let status = unsafe {
            // SAFETY: input consists of complete 192-byte elements, and output
            // has 32 writable bytes. Both buffers outlive the synchronous call.
            solana_define_syscall::definitions::sol_alt_bn128_group_op(
                solana_bn254::prelude::ALT_BN128_PAIRING_BE,
                self.input.as_ptr(),
                self.input.len() as u64,
                self.output.as_mut_ptr(),
            )
        };
        #[cfg(not(target_os = "solana"))]
        let status = {
            let result = solana_bn254::prelude::alt_bn128_pairing_be(&self.input)
                .map_err(|error| Error::SyscallFailed(error.into()))?;
            self.output.copy_from_slice(&result);
            0
        };
        let mut expected = [0; 32];
        expected[31] = 1;
        check_output(status, &self.output, &expected)
    }
}
